/**
 * Neorhiza official-logo pipeline (cross-platform).
 *
 * Source of truth: the official files supplied by the brand in
 * brand/originals/. They are copied BYTE-FOR-BYTE into public/images/logo/.
 * No geometry, color or typography inside those files is ever altered.
 *
 * The only derived logo variant is the one the brand rules allow:
 *  - neorhiza-horizontal-reversed-transparent.svg — the official reversed
 *    lockup with its solid background <rect> removed, for deep-teal surfaces.
 *
 * Other derived assets (not new logo variants):
 *  - src/app/icon.svg — exact copy of the official icon (favicon)
 *  - src/app/apple-icon.png — 180px, resized from the official iOS app icon
 *  - public/icons/icon-192.png / icon-512.png — from the official Android icon
 *  - src/assets/og/neorhiza-horizontal-reversed.png — 2x raster of the
 *    sanctioned reversed-transparent lockup for OG images, rendered in
 *    Chromium with Manrope so the wordmark is accurate
 *  - src/components/ui/brand-lockups.generated.ts — the official SVG markup
 *    as strings for inline rendering (only the root width/height attributes
 *    are dropped so CSS can size them)
 *
 * The Manrope web font (src/assets/fonts/manrope-latin-var.woff2) is a
 * subset of Manrope-Variable.ttf; regenerate it with fonttools:
 *   pyftsubset src/assets/fonts/Manrope-Variable.ttf --flavor=woff2 \
 *     --layout-features=kern,liga,calt \
 *     --unicodes="U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DC,U+2010-2027,U+2030-203A,U+2122,U+2190-2193,U+2212,U+2248" \
 *     --output-file=src/assets/fonts/manrope-latin-var.woff2
 *
 * Run: npm run generate:logos
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { chromium } from "@playwright/test";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ORIGINALS = join(ROOT, "brand/originals");
const LOGO = join(ROOT, "public/images/logo");
const ICONS = join(ROOT, "public/icons");
const APP = join(ROOT, "src/app");
const OG = join(ROOT, "src/assets/og");

const official = (name) => readFileSync(join(ORIGINALS, name), "utf8");
const write = (path, content) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
};

/* 1. The five official lockups — byte-identical copies. */
const OFFICIAL_FILES = [
  "neorhiza-icon.svg",
  "neorhiza-horizontal.svg",
  "neorhiza-stacked.svg",
  "neorhiza-horizontal-onecolor.svg",
  "neorhiza-horizontal-reversed.svg",
];
mkdirSync(LOGO, { recursive: true });
for (const name of OFFICIAL_FILES) {
  copyFileSync(join(ORIGINALS, name), join(LOGO, name));
  console.log(`official  → public/images/logo/${name}`);
}

/* 2. The single sanctioned variant: reversed lockup without its background rect. */
const reversedTransparent = official("neorhiza-horizontal-reversed.svg").replace(
  /<rect\b[^>]*\/>\s*/,
  ""
);
write(join(LOGO, "neorhiza-horizontal-reversed-transparent.svg"), reversedTransparent);
console.log("derived   → public/images/logo/neorhiza-horizontal-reversed-transparent.svg");

/* 3. Favicon and app icons. */
copyFileSync(join(ORIGINALS, "neorhiza-icon.svg"), join(APP, "icon.svg"));
console.log("derived   → src/app/icon.svg");

await sharp(join(ORIGINALS, "Neorhiza_iPhone_App_Icon_1024.png"))
  .resize(180, 180, { fit: "cover" })
  .png()
  .toFile(join(APP, "apple-icon.png"));
console.log("raster    → src/app/apple-icon.png (180)");

mkdirSync(ICONS, { recursive: true });
copyFileSync(join(ORIGINALS, "Neorhiza_Android_App_Icon_512.png"), join(ICONS, "icon-512.png"));
await sharp(join(ORIGINALS, "Neorhiza_Android_App_Icon_512.png"))
  .resize(192, 192, { fit: "cover" })
  .png()
  .toFile(join(ICONS, "icon-192.png"));
console.log("raster    → public/icons/icon-512.png, icon-192.png");

/* 4. Inline-SVG lockup module. */
const inlineReady = (svg) =>
  svg.replace(/(<svg\b[^>]*?)\s+width="[^"]*"\s+height="[^"]*"/, "$1").trim();

write(
  join(ROOT, "src/components/ui/brand-lockups.generated.ts"),
  `// AUTO-GENERATED by scripts/generate-logos.mjs from the official logo
// files in brand/originals/. Do not edit — rerun \`npm run generate:logos\`.
// Only the root width/height attributes are removed so CSS can size the
// lockups. The wordmark font is resolved by the .brand-lockup rule in
// src/styles/globals.css (Manrope via next/font).

export const HORIZONTAL_LIGHT_SVG = \`${inlineReady(official("neorhiza-horizontal.svg"))}\`;

export const HORIZONTAL_REVERSED_SVG = \`${inlineReady(reversedTransparent)}\`;

export const STACKED_LIGHT_SVG = \`${inlineReady(official("neorhiza-stacked.svg"))}\`;
`
);
console.log("module    → src/components/ui/brand-lockups.generated.ts");

/* 5. OG raster of the sanctioned reversed lockup (transparent, 2x). */
const font = readFileSync(join(ROOT, "src/assets/fonts/manrope-latin-var.woff2")).toString("base64");
const browser = await chromium.launch(
  process.env.PLAYWRIGHT_CHROMIUM_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH } : {}
);
const page = await browser.newPage({ viewport: { width: 600, height: 200 }, deviceScaleFactor: 2 });
await page.setContent(
  `<!doctype html><style>
    @font-face{font-family:Manrope;src:url(data:font/woff2;base64,${font}) format("woff2");font-weight:200 800}
    html,body{margin:0;background:transparent}
    svg{display:block;width:600px;height:200px}
  </style>${inlineReady(reversedTransparent)}`
);
await page.evaluate(() => document.fonts.ready);
mkdirSync(OG, { recursive: true });
await page.screenshot({
  path: join(OG, "neorhiza-horizontal-reversed.png"),
  omitBackground: true,
  clip: { x: 0, y: 0, width: 600, height: 200 },
});
await browser.close();
console.log("raster    → src/assets/og/neorhiza-horizontal-reversed.png (1200x400)");

console.log("\nOfficial logo pipeline complete.");
